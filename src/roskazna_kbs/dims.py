def _norm(text: str) -> str:
    return norm_header(text)


def classify_level(header: str) -> str:
    """Уровень бюджета по самой нижней части заголовка графы, где он назван.

    «ИТОГО» — уровень ``total`` только если в заголовке нет другого уровня
    (в балансе 2012 г. «консолидированный бюджет / итого» — итог по видам деятельности).
    """
    parts = [_norm(p) for p in header.split(" / ") if p.strip()]
    for part in reversed(parts):
        for code, rx in _LEVEL_RULES:
            if code != "total" and rx.search(part):
                return code
    if any(_TOTAL_RE.search(p) for p in parts):
        return "total"
    return "none"


_TOTAL_RE = re.compile(r"^\s*(итого|всего)\s*$", re.I)

# Вид деятельности — третье измерение граф в балансе ф. 0503320 до 2013 г.
ACTIVITIES: list[tuple[str, str]] = [
    ("total", "Итого по видам деятельности"),
    ("budget", "Бюджетная деятельность"),
    ("income_generating", "Приносящая доход деятельность"),
]


def classify_activity(header: str) -> str | None:
    parts = [_norm(p).casefold() for p in header.split(" / ") if p.strip()]
    if any(p.startswith("приносящ") for p in parts):
        return "income_generating"
    if any(re.match(r"^бю?джетн\w*(\s+деятельн\w*)?$", p) for p in parts):
        return "budget"
    if len(parts) > 1 and _TOTAL_RE.search(parts[-1]) and classify_level(header) != "total":
        return "total"
    return None


def classify_measure(header: str) -> str | None:
    """Показатель по верхним частям заголовка; None — если не указан."""
    parts = [_norm(p) for p in header.split(" / ") if p.strip()]
    for part in parts:
        for code, rx in _MEASURE_RULES:
            if rx.search(part):
                return code
    return None


def classify_columns(columns) -> dict[int, tuple[str, str, str | None]]:
    """{колонка Excel: (measure, budget_level, activity)} для граф-значений макета.

    Если у графы нет показателя в шапке (объединение группы не дотянуто до
    последней графы блока), берётся показатель, общий для остальных граф блока.
    """
    out: dict[int, tuple[str, str]] = {}
    by_block: dict[int, list] = {}
    for c in columns:
        if c.role == "value":
            by_block.setdefault(c.block, []).append(c)
    for cols in by_block.values():
        measures = {c.col: classify_measure(c.header) for c in cols}
        known = {m for m in measures.values() if m}
        default = known.pop() if len(known) == 1 else None
        for c in cols:
            level = classify_level(c.header)
            m = measures[c.col]
            if m is None:
                m = default if (default and level != "none") else "amount"
            out[c.col] = (m, level, classify_activity(c.header))
    return out
